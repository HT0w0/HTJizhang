/**
 * 跨「整页重载」传递信息用的钥匙。
 *
 * 恢复账本之后界面**必须整页重载**（替换账本换掉的是主进程里的数据库连接，
 * 而四个页面是常驻挂载的、各自在内存里存着上一次取到的数据），而重载会把
 * React 的 state 全清掉 —— 提示语和「该停在哪一页」都得先写进 sessionStorage
 * 带过去。
 *
 * 集中放一份的理由和 IPC 通道名一样（CLAUDE.md §5.18）：`sessionStorage` 的键
 * **写错不会报任何错**，只是静静地读不到。症状是「恢复成功的提示没了」或者
 * 「重载后回到了错误的页面」—— 两样都像软件坏了，却都不指向真正的原因。
 *
 * 2026-10-04 独立复核抓到的正是前者：提示确实生成了、也确实写进去了，
 * 但重载后落在默认的「记一笔」页，而提示挂在被 `hidden` 的设置页里，
 * 用户一个字都看不见。下面的 ACTIVE_PAGE_KEY 就是那次的补丁。
 */

/** 恢复成功后那句「已恢复，账本现在是 N 笔账」。 */
export const RESTORE_NOTICE_KEY = 'ht-restore-notice'

/** 重载之后该停在哪一页。只在恢复前写入，其余时候读不到。 */
export const ACTIVE_PAGE_KEY = 'ht-active-page'
