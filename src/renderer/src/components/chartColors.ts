/**
 * 图表配色。
 *
 * 为什么写死十六进制色值而不是用 Tailwind 的类名：SVG 的 fill 要的是一个具体的
 * 颜色，Tailwind 的类名给不了；而且饼图的每一块和排行榜前面的小圆点**必须是同一个
 * 颜色** —— 两处各自按自己的顺序取色，只要有一处顺序不同，用户就会看到
 * 「饼图上最大那块是蓝色、排行榜第一名是红色」，然后开始怀疑哪个才是对的。
 * 所以两处都调用本文件的 colorAt()，颜色的唯一来源就是这里。
 *
 * 色值选的是各家族 600 档（和界面里收支的红绿同属一档），
 * 深浅一致，在浅色和深色背景上都看得清（这些颜色是画在 SVG 上的，
 * 不跟随 Tailwind 的明暗主题切换）。
 */
const CHART_COLORS = [
  '#2563eb', // 蓝
  '#dc2626', // 红
  '#16a34a', // 绿
  '#d97706', // 橙
  '#7c3aed', // 紫
  '#0891b2', // 青
  '#db2777', // 粉
  '#65a30d', // 草绿
  '#ea580c', // 深橙
  '#4f46e5', // 靛
  '#0d9488' // 蓝绿
] as const

/**
 * 第 index 个分类的颜色。超出配色表就从头再来一遍。
 *
 * 循环取色意味着分类超过 11 个之后颜色会重复。这是可接受的：
 * 饼图上颜色只是辅助，真正区分靠的是旁边的图例（名字 + 占比），
 * 而颜色一旦不够用，硬凑新颜色只会得到两个肉眼分不开的色。
 */
export function colorAt(index: number): string {
  return CHART_COLORS[index % CHART_COLORS.length]
}

/** 支出柱 / 收入柱的颜色。和界面上收支的红绿是同一套观感。 */
export const EXPENSE_COLOR = '#dc2626'
export const INCOME_COLOR = '#16a34a'
